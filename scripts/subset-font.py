"""Build local LCD webfonts from Google's OFL NotoSansSC[wght].ttf.

Usage: python scripts/subset-font.py path/to/NotoSansSC.ttf
Requires fonttools[woff]. UI loads first; library glyphs load on demand.
Source: https://github.com/google/fonts/tree/main/ofl/notosanssc
"""
from pathlib import Path
import sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

root = Path(__file__).resolve().parent.parent
font = TTFont(sys.argv[1])
instantiateVariableFont(font, {"wght": (400, 700)}, inplace=True)
# Whitespace glyphs may have no variation record after limiting the axis.
font["gvar"].variations = {g: font["gvar"].variations.get(g, []) for g in font.getGlyphOrder()}
available = set(font.getBestCmap())
ui = set(range(0x20, 0x250)) | set(range(0x2000, 0x2070))
for source in (root / "src").rglob("*"):
    if source.suffix in {".ts", ".tsx"}:
        ui.update(map(ord, source.read_text(encoding="utf-8")))
common = set()
for high in range(0xA1, 0xF8):
    for low in range(0xA1, 0xFF):
        try:
            common.update(map(ord, bytes([high, low]).decode("gb2312")))
        except UnicodeDecodeError:
            pass
common.update(range(0x3000, 0x3100))  # punctuation and kana
common.update(range(0xFF00, 0xFFF0))
ui &= available
common = (common & available) - ui
extended = available - ui - common

def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ",".join(f"U+{a:X}" + (f"-{b:X}" if a != b else "") for a, b in groups)

css = ["/* Generated by scripts/subset-font.py; Noto Sans SC, SIL OFL 1.1. */", ':root { --font-lcd: "ReiPod Sans", sans-serif; }']
for name, points in [("ui", ui), ("common", common), ("extended", extended)]:
    # A fresh copy keeps layout/substitution dependencies independent per shard.
    from copy import deepcopy
    part = deepcopy(font)
    options = subset.Options()
    options.flavor = "woff2"
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=points)
    sub.subset(part)
    part.flavor = "woff2"
    target = root / "public" / "fonts" / f"lcd-{name}.woff2"
    part.save(target)
    css.append("\n".join([
        "@font-face {",
        '  font-family: "ReiPod Sans";',
        f'  src: url("/fonts/lcd-{name}.woff2") format("woff2");',
        "  font-style: normal;",
        "  font-weight: 400 700;",
        "  font-display: swap;",
        f"  unicode-range: {ranges(points)};",
        "}",
    ]))
    print(f"{target.name}: {len(points)} characters, {target.stat().st_size:,} bytes")
(root / "src" / "fonts.css").write_text("\n\n".join(css) + "\n", encoding="utf-8")
